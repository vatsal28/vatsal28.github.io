PROMPT_FENCE_RE = re.compile(
    r"^(?P<fence>`{3,}|~{3,})[ \t]*prompt(?:[ \t]+title=(?P<q>[\"'])(?P<title>.*?)(?P=q))?[ \t]*\n"
    r"(?P<body>.*?)\n(?P=fence)[ \t]*$",
    re.M | re.S,
)
SLOT_RE = re.compile(r"\[[A-Z][^\]\n]{0,60}\]")


def clean_prompt(text: str) -> str:
    lines = text.split("\n")
    while lines and not lines[0].strip():
        lines.pop(0)
    while lines and not lines[-1].strip():
        lines.pop()
    return "\n".join(line.rstrip() for line in lines)


def render_prompt(n: int, title: str, body: str) -> str:
    title = title.strip() or "Prompt"
    escaped = html.escape(body, quote=False)
    escaped = SLOT_RE.sub(lambda m: f'<mark class="slot">{m.group(0)}</mark>', escaped)
    pid = f"prompt-{n}"
    return (
        f'<div class="prompt">\n'
        f'<div class="prompt-bar"><span class="prompt-label" id="{pid}-label">{esc(title)}</span>'
        f'<button class="copy" type="button" data-copy="{pid}" aria-describedby="{pid}-label">'
        f'<svg class="ico ico-copy" viewBox="0 0 16 16" width="16" height="16" aria-hidden="true">'
        f'<rect x="5" y="5" width="9" height="9" rx="1.5"/><path d="M11 5V3.5A1.5 1.5 0 0 0 9.5 2h-6A1.5 1.5 0 0 0 2 3.5v6A1.5 1.5 0 0 0 3.5 11H5"/></svg>'
        f'<svg class="ico ico-check" viewBox="0 0 16 16" width="16" height="16" aria-hidden="true"><path d="M3 8.5l3.2 3L13 4.5"/></svg>'
        f'<span class="copy-label">Copy</span></button></div>\n'
        f'<pre class="prompt-text" id="{pid}" tabindex="0"><code>{escaped}</code></pre>\n'
        f"</div>"
    )


class PromptPreprocessor(Preprocessor):
    def run(self, lines):
        text = "\n".join(lines)
        counter = self.md.prompt_counter

        def repl(m: re.Match) -> str:
            counter[0] += 1
            body = clean_prompt(m.group("body"))
            self.md.prompt_texts.append(body)
            placeholder = self.md.htmlStash.store(render_prompt(counter[0], m.group("title") or "", body))
            return f"\n\n{placeholder}\n\n"

        return PROMPT_FENCE_RE.sub(repl, text).split("\n")


class FigureTreeprocessor(Treeprocessor):
    def run(self, root):
        post_dir: Path | None = getattr(self.md, "post_dir", None)
        parent_map = {c: p for p in root.iter() for c in p}
        for img in list(root.iter("img")):
            src = img.get("src", "")
            if post_dir is not None and src and not re.match(r"^(?:[a-z]+:|/)", src):
                f = post_dir / src
                if f.is_file():
                    try:
                        with Image.open(f) as im:
                            img.set("width", str(im.width))
                            img.set("height", str(im.height))
                    except OSError:
                        pass
            img.set("loading", "lazy")
            img.set("decoding", "async")
        for p in list(root.iter("p")):
            kids = list(p)
            if len(kids) == 1 and kids[0].tag == "img" and not (p.text or "").strip() and not (kids[0].tail or "").strip():
                img = kids[0]
                caption = img.attrib.pop("title", None)
                p.tag = "figure"
                p.text = None
                img.tail = None
                if caption:
                    fc = etree.SubElement(p, "figcaption")
                    fc.text = caption
        for table in list(root.iter("table")):
            parent = parent_map.get(table)
            if parent is None:
                continue
            idx = list(parent).index(table)
            wrap = etree.Element("div", {"class": "table-wrap", "tabindex": "0"})
            parent.remove(table)
            wrap.append(table)
            wrap.tail = table.tail
            table.tail = None
            parent.insert(idx, wrap)


class BuildsExtension(Extension):
    def extendMarkdown(self, md):
        md.prompt_counter = [0]
        md.prompt_texts = []
        md.registerExtension(self)
        md.preprocessors.register(PromptPreprocessor(md), "builds_prompt", 30)
        md.treeprocessors.register(FigureTreeprocessor(md), "builds_figure", 5)

    def reset(self):
        pass


def make_markdown(post_dir: Path | None) -> markdown.Markdown:
    md = markdown.Markdown(
        extensions=["extra", "toc", "sane_lists", "smarty", BuildsExtension()],
        extension_configs={"toc": {"toc_depth": "2-3", "slugify": slugify_heading}},
        output_format="html",
    )
    md.post_dir = post_dir
    return md


