def cmd_new(root: Path, slug: str, today: dt.date | None = None) -> int:
    if not SLUG_RE.match(slug) or len(slug) > 40:
        print("FAILED: slug must be lowercase kebab-case ([a-z0-9-]), at most 40 characters")
        return 1
    d = root / "builds" / slug
    if (d / "post.md").exists():
        print(f"FAILED: builds/{slug}/post.md already exists")
        return 1
    today = today or dt.date.today()
    text = template("new-post.md").substitute(slug=slug, date=today.isoformat())
    (d / "img").mkdir(parents=True, exist_ok=True)
    (d / "post.md").write_bytes(text.encode("utf-8"))
    print(f"Created builds/{slug}/post.md (status: draft). Next:")
    print(f"  1. write the post, keeping the section headings that apply")
    print(f"  2. python3 scripts/builds.py images {slug} <photos/renders...> [--cover]")
    print(f"  3. python3 scripts/builds.py build && python3 scripts/builds.py check")
    return 0


def safe_stem(name: str) -> str:
    stem = re.sub(r"[^a-z0-9]+", "-", Path(name).stem.lower()).strip("-")
    return stem or "image"


def process_image(src: Path, dest: Path, max_width: int = OUT_MAX_WIDTH) -> tuple[int, int, int]:
    with Image.open(src) as im:
        im = ImageOps.exif_transpose(im)
        has_alpha = im.mode in ("RGBA", "LA") or (im.mode == "P" and "transparency" in im.info)
        im = im.convert("RGBA" if has_alpha else "RGB")
        scale = min(1.0, max_width / im.width, MAX_IMG_SIDE / max(im.size))
        if scale < 1.0:
            im = im.resize((round(im.width * scale), round(im.height * scale)), Image.LANCZOS)
        clean = Image.frombytes(im.mode, im.size, im.tobytes())  # pixels only: no EXIF/XMP/ICC/text
        dest.parent.mkdir(parents=True, exist_ok=True)
        for q in (82, 75, 68, 60, 52):
            clean.save(dest, "WEBP", quality=q, method=6)
            if dest.stat().st_size <= MAX_IMG_BYTES:
                break
        return clean.width, clean.height, dest.stat().st_size


def make_og(src: Path, dest: Path) -> None:
    with Image.open(src) as im:
        im = ImageOps.exif_transpose(im).convert("RGB")
        og = ImageOps.fit(im, (1200, 630), Image.LANCZOS, centering=(0.5, 0.5))
        clean = Image.frombytes("RGB", og.size, og.tobytes())
        clean.save(dest, "JPEG", quality=84, optimize=True, progressive=True)


def cmd_images(root: Path, slug: str, files: list[str], cover: bool) -> int:
    d = root / "builds" / slug
    if not (d / "post.md").is_file():
        print(f"FAILED: builds/{slug}/post.md does not exist; run builds.py new {slug} first")
        return 1
    rc = 0
    for i, name in enumerate(files):
        src = Path(name)
        if not src.is_file():
            print(f"FAILED: {name}: no such file")
            rc = 1
            continue
        stem = "cover" if (cover and i == 0) else safe_stem(src.name)
        dest = d / "img" / f"{stem}.webp"
        try:
            w, h, size = process_image(src, dest)
        except OSError as exc:
            print(f"FAILED: {name}: could not read image ({exc})")
            rc = 1
            continue
        print(f"  {name} -> builds/{slug}/img/{dest.name}  {w}x{h}  {size // 1024} KB  (metadata stripped)")
        if cover and i == 0:
            make_og(dest, d / "img" / "og.jpg")
            print(f"  share image -> builds/{slug}/img/og.jpg  1200x630")
            if w < 1200:
                print(f"WARNING: cover is only {w}px wide; 1200px or more looks better")
    if rc == 0:
        print("Reference images in Markdown as ![Describe the image](img/<name>.webp \"Optional caption\")")
        print("Now open every image at full size and look for windows, views, screens, post, faces and addresses.")
    return rc


def cmd_serve(root: Path, preview: bool, port: int) -> int:
    import functools
    import http.server
    directory = root / ".preview" if preview else root
    if preview and not directory.is_dir():
        print("FAILED: no preview build yet; run builds.py build --include-drafts first")
        return 1
    handler = functools.partial(http.server.SimpleHTTPRequestHandler, directory=str(directory))
    with http.server.ThreadingHTTPServer(("127.0.0.1", port), handler) as httpd:
        print(f"Serving {directory} on http://127.0.0.1:{port}/builds/  (Ctrl+C to stop)")
        try:
            httpd.serve_forever()
        except KeyboardInterrupt:
            pass
    return 0


