def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="builds.py", description="Builds section generator for vatsalmishra.org")
    ap.add_argument("--root", type=Path, default=DEFAULT_ROOT, help=argparse.SUPPRESS)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("new", help="scaffold builds/<slug>/post.md")
    p.add_argument("slug")
    p = sub.add_parser("images", help="process images into builds/<slug>/img/")
    p.add_argument("slug")
    p.add_argument("files", nargs="+")
    p.add_argument("--cover", action="store_true", help="the first file is the cover; also writes img/og.jpg")
    p = sub.add_parser("build", help="render all generated files")
    p.add_argument("--include-drafts", action="store_true", help="preview build with drafts, written to --out (default .preview/)")
    p.add_argument("--out", type=Path, default=None)
    sub.add_parser("check", help="validate posts, output, links, images and privacy")
    p = sub.add_parser("serve", help="local preview server")
    p.add_argument("--preview", action="store_true", help="serve the .preview/ build (drafts included)")
    p.add_argument("--port", type=int, default=8000)
    args = ap.parse_args(argv)
    root = args.root.resolve()
    if args.cmd == "new":
        return cmd_new(root, args.slug)
    if args.cmd == "images":
        return cmd_images(root, args.slug, args.files, args.cover)
    if args.cmd == "build":
        return cmd_build(root, args.include_drafts, args.out)
    if args.cmd == "check":
        return cmd_check(root)
    if args.cmd == "serve":
        return cmd_serve(root, args.preview, args.port)
    return 2


if __name__ == "__main__":
    sys.exit(main())
