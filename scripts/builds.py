class PageScan(HTMLParser):
    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.headings: list[int] = []
        self.ids: set[str] = set()
        self.links: list[tuple[str, str]] = []
        self.imgs: list[dict] = []
        self.tags: list[str] = []
        self.event_attrs: list[str] = []

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        self.tags.append(tag)
        if re.fullmatch(r"h[1-6]", tag):
            self.headings.append(int(tag[1]))
        if a.get("id"):
            self.ids.add(a["id"])
        for k in ("href", "src"):
            if a.get(k) is not None:
                self.links.append((k, a[k]))
        if tag == "img":
            self.imgs.append(a)
        for k, v in attrs:
            if k.lower().startswith("on"):
                self.event_attrs.append(f"<{tag} {k}>")
            if v and k in ("href", "src") and v.strip().lower().startswith("javascript:"):
                self.event_attrs.append(f"<{tag} {k}=javascript:>")

    handle_startendtag = handle_starttag


def scan_html(text: str) -> PageScan:
    s = PageScan()
    s.feed(text)
    s.close()
    return s


def check_page_html(rel: str, text: str, problems: Problems) -> None:
    s = scan_html(text)
    if s.headings.count(1) != 1:
        problems.fail(f"{rel}: must have exactly one <h1> (found {s.headings.count(1)})")
    prev = 0
    for lvl in s.headings:
        if prev and lvl > prev + 1:
            problems.fail(f"{rel}: heading level skips from h{prev} to h{lvl}")
            break
        prev = lvl
    for img in s.imgs:
        src = img.get("src", "?")
        if "alt" not in img:
            problems.fail(f"{rel}: <img src={src}> is missing alt text (use ![]() with a description, or alt=\"\" only if decorative)")
        if not img.get("width") or not img.get("height"):
            problems.fail(f"{rel}: <img src={src}> has no width/height (is the file missing?)")


def check_body_html(rel: str, body: str, problems: Problems) -> None:
    s = scan_html(body)
    for t in sorted(set(s.tags) & BANNED_BODY_TAGS):
        problems.fail(f"{rel}: <{t}> is not allowed in a post")
    for e in s.event_attrs:
        problems.fail(f"{rel}: {e} is not allowed in a post")
    for img in s.imgs:
        if "alt" not in img:
            problems.fail(f"{rel}: image {img.get('src', '?')} is missing alt text")


def strip_code(md_text: str) -> str:
    text = re.sub(r"^(`{3,}|~{3,}).*?^\1[ \t]*$", "", md_text, flags=re.M | re.S)
    text = re.sub(r"(`+)(?:(?!\1).)+?\1", "", text, flags=re.S)
    return text


def check_raw_html(rel: str, md_text: str, problems: Problems) -> None:
    text = strip_code(md_text)
    for m in re.finditer(r"<\s*/?\s*([A-Za-z][A-Za-z0-9-]*)(?=[\s/>])", text):
        tag = m.group(1).lower()
        if tag not in ALLOWED_RAW_TAGS:
            problems.fail(f"{rel}: raw HTML <{tag}> is not allowed (allowed: {', '.join(sorted(ALLOWED_RAW_TAGS))})")
    if re.search(r"<[^>]*\son[a-z]+\s*=", text, re.I):
        problems.fail(f"{rel}: on*= event attributes are not allowed")
    if re.search(r"javascript:", text, re.I):
        problems.fail(f"{rel}: javascript: URLs are not allowed")
    for m in re.finditer(r"^[ \t]+(?:`{3,}|~{3,})", md_text, re.M):
        problems.fail(f"{rel}:{line_of(md_text, m.start())}: fenced code inside a list is not supported; "
                      "indent the code 8 spaces under the list item instead (or move it out of the list)")


def resolve_link(root: Path, page_rel: str, url: str, rendered: dict[str, str]) -> tuple[str | None, str | None]:
    """Return (target_rel, fragment) for a local link, or (None, None) for external ones."""
    if re.match(r"^[a-z][a-z0-9+.-]*:", url, re.I) or url.startswith("//"):
        return None, None
    path, _, frag = url.partition("#")
    path = path.split("?", 1)[0]
    if not path:
        return page_rel, frag or None
    if path.startswith("/"):
        target = path.lstrip("/")
    else:
        base = os.path.dirname(page_rel)
        target = os.path.normpath(os.path.join(base, path)).replace(os.sep, "/")
        if path.endswith("/"):
            target += "/"
    if target in ("", ".", "./"):
        target = "index.html"
    elif target.endswith("/"):
        target += "index.html"
    elif not os.path.splitext(target)[1] and ((root / target).is_dir() or f"{target}/index.html" in rendered):
        target += "/index.html"
    return target, frag or None


def check_links(root: Path, rendered: dict[str, str], problems: Problems) -> None:
    id_cache: dict[str, set[str]] = {}

    def ids_for(rel: str) -> set[str]:
        if rel not in id_cache:
            text = rendered.get(rel)
            if text is None and (root / rel).is_file():
                text = read_text(root / rel)
            id_cache[rel] = scan_html(text).ids if text else set()
        return id_cache[rel]

    for rel, text in sorted(rendered.items()):
        if not rel.endswith(".html"):
            continue
        scope = text
        if rel == "index.html":
            s, e = text.find(MARK_START), text.find(MARK_END)
            scope = text[s:e] if s != -1 and e != -1 else ""
        for _attr, url in scan_html(scope).links:
            target, frag = resolve_link(root, rel, url, rendered)
            if target is None:
                continue
            if target not in rendered and not (root / target).is_file():
                problems.fail(f"{rel}: broken link `{url}` (no file {target})")
                continue
            if frag and target.endswith(".html") and frag not in ids_for(target):
                problems.fail(f"{rel}: link `{url}` points at a missing #{frag}")


def image_metadata(im: Image.Image) -> list[str]:
    found = []
    if im.info.get("exif") or len(im.getexif()):
        found.append("EXIF")
    if im.info.get("xmp") or im.info.get("XML:com.adobe.xmp"):
        found.append("XMP")
    if any(k in im.info for k in ("comment", "Comment", "Description", "Author", "GPS")):
        found.append("text comment")
    if getattr(im, "text", None):
        found.append("PNG text chunks")
    return found


def check_images(root: Path, problems: Problems) -> None:
    builds = root / "builds"
    if not builds.is_dir():
        return
    for f in sorted(builds.rglob("*")):
        if not f.is_file():
            continue
        rel = str(f.relative_to(root))
        if f.suffix.lower() in VIDEO_EXTS:
            problems.fail(f"{rel}: video/GIF files are not allowed in the repo (host on YouTube/Instagram and link it)")
        if f.stat().st_size > MAX_ANY_FILE_BYTES:
            problems.fail(f"{rel}: file is over 1 MB")
    for d in sorted(p for p in builds.iterdir() if p.is_dir()):
        allowed_top = {"post.md", "index.html", "img"}
        for child in sorted(d.iterdir()):
            if child.name not in allowed_top:
                problems.fail(f"builds/{d.name}/{child.name}: unexpected file (posts hold only post.md, index.html and img/)")
        img_dir = d / "img"
        if not img_dir.is_dir():
            continue
        total = 0
        for f in sorted(img_dir.rglob("*")):
            if not f.is_file():
                continue
            rel = str(f.relative_to(root))
            total += f.stat().st_size
            if f.suffix.lower() not in IMG_EXTS:
                problems.fail(f"{rel}: only .webp, .jpg or .png images are allowed")
                continue
            if f.stat().st_size > MAX_IMG_BYTES:
                problems.fail(f"{rel}: image is over 400 KB ({f.stat().st_size // 1024} KB); run builds.py images")
            try:
                with Image.open(f) as im:
                    if max(im.size) > MAX_IMG_SIDE:
                        problems.fail(f"{rel}: image is {im.width}x{im.height}; long side must be at most {MAX_IMG_SIDE}px")
                    meta = image_metadata(im)
                    if meta:
                        problems.fail(f"{rel}: image carries metadata ({', '.join(meta)}); run builds.py images to strip it")
            except OSError:
                problems.fail(f"{rel}: not a readable image")
        if total > MAX_POST_IMG_BYTES:
            problems.fail(f"builds/{d.name}/img: images total {total // 1024} KB; the limit is 4 MB per post")


def load_denylist(problems: Problems) -> list[str]:
    terms: list[str] = []
    sources = []
    env = os.environ.get("PRIVACY_DENYLIST", "")
    if env.strip():
        terms += [t.strip() for t in re.split(r"[\n,]", env) if t.strip() and not t.strip().startswith("#")]
        sources.append("PRIVACY_DENYLIST")
    path = Path(os.environ.get("BUILDS_DENYLIST_FILE", str(DENYLIST_FILE)))
    if path.is_file():
        terms += [t.strip() for t in read_text(path).split("\n") if t.strip() and not t.strip().startswith("#")]
        sources.append(str(path).replace(str(Path.home()), "~"))
    if not terms:
        problems.warn(
            "private denylist is NOT configured, so home-location terms are not being checked. "
            "Locally: put one term per line in ~/.config/vatsalmishra-builds/denylist.txt. "
            "In CI: set the PRIVACY_DENYLIST Actions secret."
        )
    return terms


def line_of(text: str, pos: int) -> int:
    return text.count("\n", 0, pos) + 1


def scan_privacy(rel: str, text: str, denylist: list[str], problems: Problems) -> None:
    for label, rx in SECRET_PATTERNS:
        for m in rx.finditer(text):
            problems.fail(f"{rel}:{line_of(text, m.start())}: possible secret ({label}): {m.group(0)[:12]}...")
    for label, rx in PRIVATE_PATTERNS:
        for m in rx.finditer(text):
            problems.fail(f"{rel}:{line_of(text, m.start())}: private data ({label}): {m.group(0)}")
    for m in IPV4_RE.finditer(text):
        if m.group(0) not in IP_ALLOWLIST:
            problems.fail(f"{rel}:{line_of(text, m.start())}: IP address {m.group(0)}")
    for m in EMAIL_RE.finditer(text):
        if m.group(0).lower() not in EMAIL_ALLOWLIST:
            problems.fail(f"{rel}:{line_of(text, m.start())}: email address {m.group(0)}")
    for label, rx in EMPLOYER_PATTERNS:
        for m in rx.finditer(text):
            problems.fail(f"{rel}:{line_of(text, m.start())}: employer-internal marker ({label}): {m.group(0)}")
    low = text.lower()
    for i, term in enumerate(denylist, 1):
        t = term.lower()
        pattern = (r"(?<!\w)" if t[:1].isalnum() else "") + re.escape(t) + (r"(?!\w)" if t[-1:].isalnum() else "")
        m = re.search(pattern, low)
        if m:
            # never print the term itself: CI logs are public
            problems.fail(f"{rel}:{line_of(text, m.start())}: matches private denylist term #{i}")


def root_block(css: str) -> str | None:
    m = re.search(r":root\s*\{(.*?)\}", css, re.S)
    if not m:
        return None
    return "\n".join(line.strip() for line in m.group(1).strip().split("\n") if line.strip())


def check_skin(root: Path, problems: Problems) -> None:
    css = root / "assets" / "css" / "builds.css"
    home = root / "index.html"
    if not css.is_file():
        problems.fail("assets/css/builds.css is missing")
        return
    if not home.is_file():
        return
    a, b = root_block(read_text(home)), root_block(read_text(css))
    if a is None or b is None:
        problems.fail("could not find a :root token block in index.html or builds.css")
    elif a != b:
        problems.fail("skin drift: the :root tokens in assets/css/builds.css differ from index.html; copy them across")


def run_checks(root: Path) -> Problems:
    problems = Problems()
    site = render_site(root, problems)

    # generated output is committed and current
    for rel, text in sorted(site.outputs.items()):
        f = root / rel
        if not f.is_file():
            problems.fail(f"{rel}: generated file is missing; run builds.py build")
        elif f.read_bytes() != text.encode("utf-8"):
            problems.fail(f"{rel}: generated file is out of date or hand-edited; run builds.py build")
    for rel in site.stale:
        problems.fail(f"{rel}: generated page for a draft or deleted post; run builds.py build to remove it")

    # html sanity + links
    for rel, text in sorted(site.outputs.items()):
        if rel.startswith("builds/") and rel.endswith(".html"):
            check_page_html(rel, text, problems)
    for p in site.posts:
        rel = f"builds/{p.slug}/post.md"
        check_raw_html(rel, p.body_md, problems)
        check_body_html(rel, p.body_html, problems)
        if p.meta.get("cover") and not (p.dir / "img" / "og.jpg").is_file():
            problems.warn(f"{rel}: has a cover but no img/og.jpg; run builds.py images {p.slug} <cover> --cover")
    check_links(root, site.outputs, problems)

    # drafts are not rendered into the repo, but their pages must still be sound
    drafts = [p for p in site.posts if p.status == "draft"]
    if drafts:
        preview = render_site(root, Problems(), include_drafts=True)
        draft_pages = {f"builds/{p.slug}/index.html" for p in drafts}
        for rel in sorted(draft_pages):
            check_page_html(rel, preview.outputs[rel], problems)
        sink = Problems()
        check_links(root, preview.outputs, sink)
        problems.failures += [f for f in sink.failures if any(f.startswith(rel) for rel in draft_pages)]

    # images
    check_images(root, problems)

    # privacy, secrets, employer flags (drafts too: the repo is public)
    denylist = load_denylist(problems)
    builds = root / "builds"
    if builds.is_dir():
        for f in sorted(builds.rglob("*")):
            if f.is_file() and f.suffix in (".md", ".html", ".xml"):
                scan_privacy(str(f.relative_to(root)), read_text(f), denylist, problems)
    for rel in ("sitemap.xml",):
        if (root / rel).is_file():
            scan_privacy(rel, read_text(root / rel), denylist, problems)
    if "index.html" in site.outputs:
        text = site.outputs["index.html"]
        s, e = text.find(MARK_START), text.find(MARK_END)
        scan_privacy("index.html (builds block)", text[s:e], denylist, problems)

    check_skin(root, problems)
    # dedupe while keeping order
    problems.failures = list(dict.fromkeys(problems.failures))
    problems.warnings = list(dict.fromkeys(problems.warnings))
    return problems


def cmd_check(root: Path) -> int:
    problems = run_checks(root)
    problems.report()
    posts = discover_posts(root, Problems())
    pub = sum(1 for p in posts if p.status == "published")
    if problems.failures:
        print(f"builds check: {len(problems.failures)} problem(s)")
        return 1
    print(f"OK: builds check passed ({pub} published, {len(posts) - pub} draft, {len(problems.warnings)} warning(s))")
    return 0


