def head_extra(noindex: bool) -> str:
    return '  <meta name="robots" content="noindex">\n' if noindex else ""


def render_page(root: Path, *, title: str, description: str, canonical: str, og_type: str,
                og_image: str, og_image_alt: str, body: str, nav_current: str,
                noindex: bool = False, extra_head: str = "", jsonld: dict | None = None) -> str:
    ld = ""
    if jsonld:
        ld = ('  <script type="application/ld+json">\n'
              + json.dumps(jsonld, indent=2, ensure_ascii=False, sort_keys=True).replace("</", "<\\/")
              + "\n  </script>\n")
    nav = []
    for label, href, key in (("Home", "/", "home"), ("Builds", "/builds/", "builds"), ("Contact", "/#contact", "contact")):
        cur = ' aria-current="page"' if key == nav_current else ""
        nav.append(f'<a href="{href}"{cur}>{label}</a>')
    return template("page.html").substitute(
        banner=BANNER,
        title=esc(title),
        description=esc(description),
        canonical=esc(canonical),
        og_type=og_type,
        og_image=esc(og_image),
        og_image_alt=esc(og_image_alt),
        robots=head_extra(noindex),
        extra_head=extra_head,
        jsonld=ld,
        css_v=asset_version(root, "assets/css/builds.css"),
        js_v=asset_version(root, "assets/js/builds.js"),
        nav="\n      ".join(nav),
        body=body,
    )


def tag_list(tags: list[str]) -> str:
    return '<ul class="tags" aria-label="Tags">' + "".join(f'<li class="tag">{esc(t)}</li>' for t in tags) + "</ul>"


def toc_html(tokens: list, cls: str) -> str:
    def items(toks: list) -> str:
        out = []
        for t in toks:
            name = html.escape(html.unescape(re.sub(r"<[^>]+>", "", t["name"])), quote=False)
            child = f"\n<ol>{items(t['children'])}</ol>" if t.get("children") else ""
            out.append(f'<li><a href="#{esc(t["id"])}">{name}</a>{child}</li>')
        return "".join(out)
    return f'<ol class="{cls}">{items(tokens)}</ol>'


def render_post(root: Path, post: Post, newer: Post | None, older: Post | None, preview: bool) -> str:
    meta = post.meta
    show_toc = sum(1 for t in post.toc if t["level"] == 2) >= TOC_MIN_H2
    has_og = (post.dir / "img" / "og.jpg").is_file()
    og_image = f"{SITE}/builds/{post.slug}/img/og.jpg" if has_og else DEFAULT_OG
    og_alt = meta.get("cover_alt") or "VatsalOS card for Vatsal Mishra"

