@dataclass
class SiteRender:
    outputs: dict[str, str]
    posts: list[Post]
    listed: list[Post]
    stale: list[str]


def render_site(root: Path, problems: Problems, include_drafts: bool = False) -> SiteRender:
    posts = discover_posts(root, problems)
    for p in posts:
        render_body(p)
    listed = [p for p in posts if p.status == "published" or include_drafts]
    published = [p for p in posts if p.status == "published"]
    outputs: dict[str, str] = {}
    for i, p in enumerate(listed):
        newer = listed[i - 1] if i > 0 else None
        older = listed[i + 1] if i + 1 < len(listed) else None
        outputs[f"builds/{p.slug}/index.html"] = render_post(root, p, newer, older, include_drafts)
    outputs["builds/index.html"] = render_index(root, listed)
    outputs["builds/feed.xml"] = render_feed(published)
    outputs["sitemap.xml"] = render_sitemap(published)
    outputs["robots.txt"] = render_robots()
    home = root / "index.html"
    if home.is_file():
        new_home = replace_home_block(read_text(home), render_home_block(listed))
        if new_home is None:
            problems.warn("index.html has no BUILDS:START/END markers; homepage block not generated")
        else:
            outputs["index.html"] = new_home
    stale = []
    builds = root / "builds"
    if builds.is_dir():
        for d in sorted(p for p in builds.iterdir() if p.is_dir()):
            rel = f"builds/{d.name}/index.html"
            f = d / "index.html"
            if rel not in outputs and f.is_file() and BANNER in read_text(f)[:300]:
                stale.append(rel)
    return SiteRender(outputs=outputs, posts=posts, listed=listed, stale=stale)


def cmd_build(root: Path, include_drafts: bool, out: Path | None) -> int:
    if include_drafts:
        out = out or (root / ".preview")
        if out.resolve() == root.resolve():
            print("FAILED: --include-drafts must write to a separate --out directory, never the repo")
            return 1
        if out.exists():
            shutil.rmtree(out)
        shutil.copytree(root, out, ignore=shutil.ignore_patterns(".git", ".venv", ".preview", "__pycache__", "node_modules"))
        root = out
    problems = Problems()
    site = render_site(root, problems, include_drafts=include_drafts)
    if problems.failures:
        problems.report()
        print("Build stopped: fix the problems above.")
        return 1
    changed = [rel for rel, text in sorted(site.outputs.items()) if write_if_changed(root / rel, text)]
    for rel in site.stale:
        (root / rel).unlink()
        changed.append(f"{rel} (removed)")
    problems.report()
    pub = sum(1 for p in site.posts if p.status == "published")
    print(f"Built {len(site.outputs)} files ({pub} published, {len(site.posts) - pub} draft"
          f"{', drafts INCLUDED' if include_drafts else ''}) into {root}")
    for rel in changed:
        print(f"  wrote {rel}")
    if include_drafts:
        print(f"Preview only. Serve with: python3 -m http.server 8000 --bind 127.0.0.1 --directory {root}")
    return 0


