class Problems:
    def __init__(self) -> None:
        self.failures: list[str] = []
        self.warnings: list[str] = []

    def fail(self, msg: str) -> None:
        self.failures.append(msg)

    def warn(self, msg: str) -> None:
        self.warnings.append(msg)

    def report(self, out=sys.stdout) -> None:
        for w in self.warnings:
            print(f"WARNING: {w}", file=out)
        for f in self.failures:
            print(f"FAILED: {f}", file=out)


def esc(text: str) -> str:
    return html.escape(str(text), quote=True)


def human_date(d: dt.date) -> str:
    return f"{d.day} {MONTHS[d.month - 1]} {d.year}"


def iso_ts(d: dt.date) -> str:
    return f"{d.isoformat()}T00:00:00Z"


def read_text(path: Path) -> str:
    return path.read_bytes().decode("utf-8").replace("\r\n", "\n").replace("\r", "\n")


def write_if_changed(path: Path, text: str) -> bool:
    data = text.encode("utf-8")
    if path.exists() and path.read_bytes() == data:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    return True


def asset_version(root: Path, rel: str) -> str:
    p = root / rel
    if not p.exists():
        return "0"
    return hashlib.sha256(read_text(p).encode("utf-8")).hexdigest()[:10]


def template(name: str) -> string.Template:
    return string.Template(read_text(TEMPLATES / name))


def slugify_heading(value: str, separator: str = "-") -> str:
    value = html.unescape(re.sub(r"<[^>]+>", "", value))
    value = value.replace("’", "").replace("'", "")
    value = re.sub(r"[^\w\s-]", "", value.lower()).strip()
    return re.sub(r"[\s_-]+", separator, value) or "section"


def norm_heading(text: str) -> str:
    text = html.unescape(re.sub(r"<[^>]+>", "", text))
    text = text.replace("’", "'").replace("‘", "'")
    return re.sub(r"\s+", " ", text).strip().rstrip(":").lower()


def to_date(value, key: str, problems: Problems, where: str) -> dt.date | None:
    if isinstance(value, dt.datetime):
        return value.date()
    if isinstance(value, dt.date):
        return value
    if isinstance(value, str) and re.fullmatch(r"\d{4}-\d{2}-\d{2}", value):
        try:
            return dt.date.fromisoformat(value)
        except ValueError:
            pass
    problems.fail(f"{where}: `{key}` must be an ISO date like 2026-11-21 (got {value!r})")
    return None


